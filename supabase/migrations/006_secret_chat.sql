-- 006: Secret Chat — end-to-end encrypted, disappearing rooms.
--
-- The server stores and relays MLS ciphertext only. It never sees message text, file
-- names or file keys. Rules enforced here, not in the browser:
--   * Default deny: RLS on every table, no direct table grants to anon/authenticated.
--     All access goes through the security-definer functions below, which check membership.
--   * Expiry uses the database clock (now()), never the client's.
--   * Invite tokens and room access codes are stored only as hashes.
--   * Realtime pings carry ids only, and only the server can publish them.
-- Additive only: new chat_* objects, nothing existing is altered. Rollback: 006_secret_chat_down.sql.

create extension if not exists pgcrypto with schema extensions;

-- Devices: one per browser/app install. Guests are anonymous Supabase users with a device too.
create table if not exists public.chat_devices (
  id            uuid primary key default gen_random_uuid(),
  owner         uuid not null references auth.users(id) on delete cascade,
  label         text check (char_length(label) <= 60),
  signature_pub bytea not null,
  created_at    timestamptz not null default now(),
  last_seen     timestamptz not null default now(),
  revoked_at    timestamptz
);
create index if not exists chat_devices_owner on public.chat_devices(owner) where revoked_at is null;

-- One-time MLS KeyPackages a device publishes so it can be added to a room.
create table if not exists public.chat_key_packages (
  id          uuid primary key default gen_random_uuid(),
  device_id   uuid not null references public.chat_devices(id) on delete cascade,
  key_package bytea not null check (octet_length(key_package) <= 4096),
  created_at  timestamptz not null default now(),
  consumed_at timestamptz
);
create index if not exists chat_key_packages_free on public.chat_key_packages(device_id, created_at) where consumed_at is null;

create table if not exists public.chat_rooms (
  id               uuid primary key default gen_random_uuid(),
  kind             text not null check (kind in ('quick','secret','business')),
  owner            uuid not null references auth.users(id) on delete cascade,
  state            text not null default 'active' check (state in ('active','burned')),
  default_ttl_s    int  not null default 60 check (default_ttl_s between 10 and 86400),
  expiry_mode      text not null default 'on_open' check (expiry_mode in ('on_send','on_open')),
  max_unopened_s   int  not null default 604800 check (max_unopened_s between 60 and 604800),
  access_code_hash text,                       -- bcrypt via pgcrypto; null = no code
  next_seq         bigint not null default 1,  -- per-room ordering
  created_at       timestamptz not null default now(),
  expires_at       timestamptz not null,
  burned_at        timestamptz
);
create index if not exists chat_rooms_expiry on public.chat_rooms(expires_at) where state = 'active';

create table if not exists public.chat_members (
  room_id    uuid not null references public.chat_rooms(id) on delete cascade,
  device_id  uuid not null references public.chat_devices(id) on delete cascade,
  user_id    uuid not null references auth.users(id) on delete cascade,
  role       text not null default 'member' check (role in ('owner','member')),
  state      text not null default 'pending' check (state in ('pending','active','removed')),
  key_package bytea,                            -- set while pending, cleared once added
  joined_at  timestamptz not null default now(),
  removed_at timestamptz,
  primary key (room_id, device_id)
);
create index if not exists chat_members_user on public.chat_members(user_id) where state <> 'removed';

create table if not exists public.chat_invites (
  id                uuid primary key default gen_random_uuid(),
  room_id           uuid not null references public.chat_rooms(id) on delete cascade,
  token_hash        bytea not null unique,      -- sha256(token); the token itself is never stored
  expires_at        timestamptz not null,
  max_uses          int not null default 1 check (max_uses between 1 and 100),
  uses              int not null default 0,
  requires_approval boolean not null default false,
  revoked_at        timestamptz,
  created_by        uuid not null references auth.users(id) on delete cascade,
  created_at        timestamptz not null default now()
);
create index if not exists chat_invites_room on public.chat_invites(room_id);

-- MLS messages. kind: app (chat content), commit (membership/key changes), welcome (to one new device).
create table if not exists public.chat_messages (
  id              uuid primary key,             -- generated by the sender: idempotency key
  room_id         uuid not null references public.chat_rooms(id) on delete cascade,
  seq             bigint not null,
  sender_device   uuid not null references public.chat_devices(id) on delete cascade,
  to_device       uuid references public.chat_devices(id) on delete cascade,
  kind            text not null check (kind in ('app','commit','welcome')),
  epoch           bigint not null,
  ciphertext      bytea not null check (octet_length(ciphertext) <= 65536),
  ttl_s           int not null check (ttl_s between 10 and 86400),
  created_at      timestamptz not null default now(),
  hard_expires_at timestamptz not null,
  unique (room_id, seq)
);
create index if not exists chat_messages_fetch on public.chat_messages(room_id, seq);
create index if not exists chat_messages_hard_expiry on public.chat_messages(hard_expires_at);

-- Per-recipient-device delivery and expiry for app messages.
create table if not exists public.chat_deliveries (
  message_id   uuid not null references public.chat_messages(id) on delete cascade,
  device_id    uuid not null references public.chat_devices(id) on delete cascade,
  delivered_at timestamptz,
  opened_at    timestamptz,
  expires_at   timestamptz,                     -- null until opened when expiry_mode = on_open
  primary key (message_id, device_id)
);
create index if not exists chat_deliveries_expiry on public.chat_deliveries(expires_at) where expires_at is not null;
create index if not exists chat_deliveries_device on public.chat_deliveries(device_id);

create table if not exists public.chat_attachments (
  id          uuid primary key default gen_random_uuid(),
  room_id     uuid not null references public.chat_rooms(id) on delete cascade,
  object_path text not null unique,             -- chat-attachments/<room_id>/<id>
  size        bigint not null check (size between 1 and 52428800),
  view_once   boolean not null default false,
  created_at  timestamptz not null default now(),
  expires_at  timestamptz not null,
  revoked_at  timestamptz
);
create index if not exists chat_attachments_expiry on public.chat_attachments(expires_at);

-- Storage objects whose rows are gone and must be removed by the cleanup route.
create table if not exists public.chat_storage_trash (
  object_path text primary key,
  queued_at   timestamptz not null default now()
);

-- Minimal security log: no IPs, no content, kept 30 days.
create table if not exists public.chat_security_events (
  id         bigint generated always as identity primary key,
  kind       text not null,
  room_id    uuid,
  device_id  uuid,
  created_at timestamptz not null default now()
);
create index if not exists chat_security_events_time on public.chat_security_events(created_at);

create table if not exists public.chat_rate_limits (
  bucket       text not null,
  key_hash     bytea not null,
  window_start timestamptz not null,
  hits         int not null default 0,
  primary key (bucket, key_hash, window_start)
);

create table if not exists public.chat_admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);

-- Default deny everywhere.
do $$ declare t text; begin
  foreach t in array array['chat_devices','chat_key_packages','chat_rooms','chat_members','chat_invites',
    'chat_messages','chat_deliveries','chat_attachments','chat_storage_trash','chat_security_events',
    'chat_rate_limits','chat_admins'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon, authenticated', t);
    execute format('grant all on public.%I to service_role', t);
  end loop;
end $$;

-- ---------------------------------------------------------------------------- helpers

create or replace function public.chat_log(p_kind text, p_room uuid default null, p_device uuid default null)
returns void language sql security definer set search_path = public as $$
  insert into chat_security_events(kind, room_id, device_id) values (p_kind, p_room, p_device);
$$;

-- Fixed-window limiter. Returns false once `p_max` hits happen within `p_window`.
create or replace function public.chat_rate_ok(p_bucket text, p_key text, p_max int, p_window interval)
returns boolean language plpgsql security definer set search_path = public, extensions as $$
declare w timestamptz := to_timestamp(floor(extract(epoch from now()) / extract(epoch from p_window)) * extract(epoch from p_window));
        n int;
begin
  insert into chat_rate_limits(bucket, key_hash, window_start, hits)
  values (p_bucket, digest(p_key, 'sha256'), w, 1)
  on conflict (bucket, key_hash, window_start) do update set hits = chat_rate_limits.hits + 1
  returning hits into n;
  if n > p_max then perform chat_log('rate_limited:' || p_bucket); return false; end if;
  return true;
end $$;

-- The caller's own, non-revoked device. Raises if it isn't theirs.
create or replace function public.chat_my_device(p_device uuid)
returns uuid language plpgsql stable security definer set search_path = public as $$
begin
  if auth.uid() is null then raise exception 'not_signed_in'; end if;
  if not exists (select 1 from chat_devices where id = p_device and owner = auth.uid() and revoked_at is null) then
    raise exception 'device_not_found';
  end if;
  return p_device;
end $$;

create or replace function public.chat_is_member(p_room uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from chat_members m join chat_rooms r on r.id = m.room_id
    join chat_devices d on d.id = m.device_id
    where m.room_id = p_room and m.user_id = auth.uid() and m.state = 'active'
      and d.revoked_at is null and r.state = 'active' and r.expires_at > now());
$$;

create or replace function public.chat_ping(p_room uuid, p_event text, p_payload jsonb)
returns void language plpgsql security definer set search_path = public as $$
begin
  perform realtime.send(p_payload, p_event, 'room:' || p_room::text, true);
exception when others then null;  -- Realtime is a hint; clients also poll on reconnect.
end $$;

-- ---------------------------------------------------------------------------- devices & keys

create or replace function public.chat_register_device(p_signature_pub bytea, p_label text default null)
returns uuid language plpgsql security definer set search_path = public as $$
declare v uuid;
begin
  if auth.uid() is null then raise exception 'not_signed_in'; end if;
  if octet_length(p_signature_pub) not between 32 and 256 then raise exception 'bad_key'; end if;
  if not chat_rate_ok('device', auth.uid()::text, 20, interval '1 hour') then raise exception 'rate_limited'; end if;
  insert into chat_devices(owner, signature_pub, label) values (auth.uid(), p_signature_pub, left(p_label, 60)) returning id into v;
  perform chat_log('device_registered', null, v);
  return v;
end $$;

create or replace function public.chat_upload_key_packages(p_device uuid, p_packages bytea[])
returns int language plpgsql security definer set search_path = public as $$
begin
  perform chat_my_device(p_device);
  if coalesce(array_length(p_packages, 1), 0) > 50 then raise exception 'too_many'; end if;
  insert into chat_key_packages(device_id, key_package) select p_device, unnest(p_packages);
  update chat_devices set last_seen = now() where id = p_device;
  return coalesce(array_length(p_packages, 1), 0);
end $$;

create or replace function public.chat_list_devices()
returns table (id uuid, label text, created_at timestamptz, last_seen timestamptz, revoked_at timestamptz)
language sql stable security definer set search_path = public as $$
  select id, label, created_at, last_seen, revoked_at from chat_devices where owner = auth.uid() order by created_at desc;
$$;

-- Revoking a device removes it from every room (the other members' clients then commit the MLS removal).
create or replace function public.chat_revoke_device(p_device uuid)
returns void language plpgsql security definer set search_path = public as $$
declare r record;
begin
  update chat_devices set revoked_at = now() where id = p_device and owner = auth.uid() and revoked_at is null;
  if not found then raise exception 'device_not_found'; end if;
  delete from chat_key_packages where device_id = p_device;
  for r in update chat_members set state = 'removed', removed_at = now()
           where device_id = p_device and state <> 'removed' returning room_id loop
    perform chat_ping(r.room_id, 'member_removed', jsonb_build_object('device', p_device));
  end loop;
  perform chat_log('device_revoked', null, p_device);
end $$;

-- ---------------------------------------------------------------------------- rooms

create or replace function public.chat_create_room(
  p_device uuid, p_kind text, p_ttl_s int default null, p_expiry_mode text default 'on_open',
  p_room_lifetime_s int default 86400, p_access_code text default null)
returns uuid language plpgsql security definer set search_path = public, extensions as $$
declare v uuid;
begin
  perform chat_my_device(p_device);
  if not chat_rate_ok('room_create', auth.uid()::text, 30, interval '1 hour') then raise exception 'rate_limited'; end if;
  if p_room_lifetime_s not between 300 and 2592000 then raise exception 'bad_lifetime'; end if;
  if p_access_code is not null and char_length(p_access_code) < 6 then raise exception 'weak_code'; end if;
  insert into chat_rooms(kind, owner, default_ttl_s, expiry_mode, access_code_hash, expires_at)
  values (p_kind, auth.uid(),
          coalesce(p_ttl_s, case p_kind when 'secret' then 30 else 60 end),
          coalesce(p_expiry_mode, 'on_open'),
          case when p_access_code is null then null else crypt(p_access_code, gen_salt('bf', 10)) end,
          now() + make_interval(secs => p_room_lifetime_s))
  returning id into v;
  insert into chat_members(room_id, device_id, user_id, role, state) values (v, p_device, auth.uid(), 'owner', 'active');
  return v;
end $$;

create or replace function public.chat_my_rooms()
returns table (id uuid, kind text, role text, member_state text, default_ttl_s int, expiry_mode text, expires_at timestamptz, created_at timestamptz)
language sql stable security definer set search_path = public as $$
  select r.id, r.kind, m.role, m.state, r.default_ttl_s, r.expiry_mode, r.expires_at, r.created_at
  from chat_members m join chat_rooms r on r.id = m.room_id
  where m.user_id = auth.uid() and m.state <> 'removed' and r.state = 'active' and r.expires_at > now()
  order by r.created_at desc;
$$;

create or replace function public.chat_room_members(p_room uuid)
returns table (device_id uuid, role text, state text, signature_pub bytea, key_package bytea)
language plpgsql stable security definer set search_path = public as $$
begin
  if not chat_is_member(p_room) then raise exception 'not_a_member'; end if;
  return query select m.device_id, m.role, m.state, d.signature_pub, m.key_package
    from chat_members m join chat_devices d on d.id = m.device_id
    where m.room_id = p_room and m.state <> 'removed' and d.revoked_at is null;
end $$;

create or replace function public.chat_set_timer(p_room uuid, p_ttl_s int, p_expiry_mode text)
returns void language plpgsql security definer set search_path = public as $$
begin
  update chat_rooms set default_ttl_s = p_ttl_s, expiry_mode = p_expiry_mode
  where id = p_room and owner = auth.uid() and state = 'active';
  if not found then raise exception 'not_owner'; end if;
  perform chat_ping(p_room, 'room_updated', jsonb_build_object('ttl', p_ttl_s, 'mode', p_expiry_mode));
end $$;

-- ---------------------------------------------------------------------------- invites

create or replace function public.chat_create_invite(p_room uuid, p_token text, p_expires_s int default 86400,
  p_max_uses int default 1, p_requires_approval boolean default false)
returns uuid language plpgsql security definer set search_path = public, extensions as $$
declare v uuid;
begin
  if not exists (select 1 from chat_members where room_id = p_room and user_id = auth.uid() and role = 'owner' and state = 'active')
     and not exists (select 1 from chat_rooms where id = p_room and kind = 'quick') then
    raise exception 'not_owner';
  end if;
  if not chat_is_member(p_room) then raise exception 'not_a_member'; end if;
  if char_length(p_token) < 32 then raise exception 'weak_token'; end if;
  if p_expires_s not between 60 and 604800 then raise exception 'bad_expiry'; end if;
  insert into chat_invites(room_id, token_hash, expires_at, max_uses, requires_approval, created_by)
  values (p_room, digest(p_token, 'sha256'), least(now() + make_interval(secs => p_expires_s), (select expires_at from chat_rooms where id = p_room)),
          p_max_uses, p_requires_approval, auth.uid())
  returning id into v;
  return v;
end $$;

create or replace function public.chat_revoke_invite(p_invite uuid)
returns void language plpgsql security definer set search_path = public as $$
begin
  update chat_invites i set revoked_at = now()
  where i.id = p_invite and i.revoked_at is null
    and (i.created_by = auth.uid() or exists (select 1 from chat_rooms r where r.id = i.room_id and r.owner = auth.uid()));
  if not found then raise exception 'not_found'; end if;
end $$;

create or replace function public.chat_list_invites(p_room uuid)
returns table (id uuid, expires_at timestamptz, max_uses int, uses int, requires_approval boolean, revoked_at timestamptz)
language plpgsql stable security definer set search_path = public as $$
begin
  if not chat_is_member(p_room) then raise exception 'not_a_member'; end if;
  return query select i.id, i.expires_at, i.max_uses, i.uses, i.requires_approval, i.revoked_at
    from chat_invites i where i.room_id = p_room order by i.created_at desc;
end $$;

-- What a joiner sees before redeeming: only whether a code is needed. Unknown, used up,
-- revoked and expired tokens all look the same, so the response can't be used to probe.
create or replace function public.chat_peek_invite(p_token text)
returns table (needs_code boolean, kind text)
language plpgsql security definer set search_path = public, extensions as $$
begin
  if not chat_rate_ok('invite_peek', coalesce(auth.uid()::text, 'anon'), 60, interval '10 minutes') then raise exception 'rate_limited'; end if;
  return query select r.access_code_hash is not null, r.kind
    from chat_invites i join chat_rooms r on r.id = i.room_id
    where i.token_hash = digest(p_token, 'sha256') and i.revoked_at is null and i.expires_at > now()
      and i.uses < i.max_uses and r.state = 'active' and r.expires_at > now();
end $$;

-- Redeems an invite for one device: atomically counts the use and adds the device as a
-- pending member with its KeyPackage. An active member's client then commits the MLS add
-- (immediately, or after the owner approves when the invite requires approval).
-- Failures are returned, not raised: raising would roll back the rate-limit counters and the
-- security log, which would make wrong access codes free to retry.
create or replace function public.chat_redeem_invite(p_token text, p_device uuid, p_key_package bytea, p_access_code text default null)
returns table (joined_room uuid, error text) language plpgsql security definer set search_path = public, extensions as $$
declare i chat_invites%rowtype; r chat_rooms%rowtype;
begin
  perform chat_my_device(p_device);
  if octet_length(p_key_package) not between 64 and 4096 then raise exception 'bad_key_package'; end if;
  if not chat_rate_ok('invite_redeem', auth.uid()::text, 10, interval '10 minutes') then
    return query select null::uuid, 'rate_limited'; return;
  end if;
  select * into i from chat_invites where token_hash = digest(p_token, 'sha256') for update;
  if found then select * into r from chat_rooms where id = i.room_id; end if;
  if i.id is null or i.revoked_at is not null or i.expires_at <= now() or i.uses >= i.max_uses
     or r.state <> 'active' or r.expires_at <= now() then
    perform chat_log('invite_invalid', i.room_id, p_device);
    return query select null::uuid, 'invite_invalid'; return;
  end if;
  if r.access_code_hash is not null then
    if not chat_rate_ok('access_code', i.room_id::text || auth.uid()::text, 5, interval '15 minutes')
       or not chat_rate_ok('access_code_room', i.room_id::text, 30, interval '15 minutes') then
      return query select null::uuid, 'rate_limited'; return;
    end if;
    if p_access_code is null or crypt(p_access_code, r.access_code_hash) <> r.access_code_hash then
      perform chat_log('access_code_wrong', r.id, p_device);
      return query select null::uuid, 'access_code_wrong'; return;
    end if;
  end if;
  update chat_invites set uses = uses + 1 where id = i.id;
  insert into chat_members(room_id, device_id, user_id, state, key_package)
  values (r.id, p_device, auth.uid(), 'pending', p_key_package)
  on conflict (room_id, device_id) do nothing;
  perform chat_ping(r.id, 'join_request', jsonb_build_object('device', p_device, 'approval', i.requires_approval));
  perform chat_log('invite_redeemed', r.id, p_device);
  return query select r.id, null::text;
end $$;

-- ---------------------------------------------------------------------------- messages

-- Sends one MLS message. Idempotent on the sender-chosen id; ordering via the room row lock.
-- For a commit that adds pending devices, pass p_activate so they become active in the same transaction.
create or replace function public.chat_send(
  p_room uuid, p_device uuid, p_id uuid, p_kind text, p_epoch bigint, p_ciphertext bytea,
  p_to_device uuid default null, p_ttl_s int default null, p_activate uuid[] default null, p_remove uuid[] default null)
returns bigint language plpgsql security definer set search_path = public as $$
declare r chat_rooms%rowtype; v_seq bigint; v_existing bigint; v_ttl int; v_hard timestamptz;
begin
  perform chat_my_device(p_device);
  select seq into v_existing from chat_messages where id = p_id and room_id = p_room and sender_device = p_device;
  if found then return v_existing; end if;  -- retry of a message we already have
  if not exists (select 1 from chat_members where room_id = p_room and device_id = p_device and state = 'active') then
    raise exception 'not_a_member';
  end if;
  select * into r from chat_rooms where id = p_room for update;
  if r.state <> 'active' or r.expires_at <= now() then raise exception 'room_closed'; end if;
  if not chat_rate_ok('send', p_device::text, 120, interval '1 minute') then raise exception 'rate_limited'; end if;
  if p_kind = 'welcome' and p_to_device is null then raise exception 'welcome_needs_recipient'; end if;
  if (p_activate is not null or p_remove is not null) and p_kind <> 'commit' then raise exception 'bad_kind'; end if;
  if p_remove is not null and r.owner <> auth.uid() and not (p_remove <@ array(
       select device_id from chat_members where room_id = p_room and state = 'removed')) then
    raise exception 'not_owner';  -- members may only commit removals the server already recorded
  end if;

  v_ttl  := least(coalesce(p_ttl_s, r.default_ttl_s), 86400);
  v_hard := least(now() + make_interval(secs => r.max_unopened_s), r.expires_at);
  v_seq  := r.next_seq;
  update chat_rooms set next_seq = next_seq + 1 where id = p_room;

  insert into chat_messages(id, room_id, seq, sender_device, to_device, kind, epoch, ciphertext, ttl_s, hard_expires_at)
  values (p_id, p_room, v_seq, p_device, p_to_device, p_kind, p_epoch, p_ciphertext, v_ttl, v_hard);

  if p_kind = 'app' then
    insert into chat_deliveries(message_id, device_id, expires_at)
    select p_id, m.device_id, case when r.expiry_mode = 'on_send' then least(now() + make_interval(secs => v_ttl), v_hard) end
    from chat_members m where m.room_id = p_room and m.state = 'active' and m.device_id <> p_device;
  end if;
  if p_activate is not null then
    update chat_members set state = 'active', key_package = null
    where room_id = p_room and device_id = any(p_activate) and state = 'pending';
  end if;
  if p_remove is not null then
    update chat_members set state = 'removed', removed_at = coalesce(removed_at, now())
    where room_id = p_room and device_id = any(p_remove);
  end if;
  perform chat_ping(p_room, 'msg', jsonb_build_object('seq', v_seq));
  return v_seq;
end $$;

-- Messages for one device after a sequence number. Expired content is never returned.
create or replace function public.chat_fetch(p_room uuid, p_device uuid, p_after bigint default 0, p_limit int default 200)
returns table (id uuid, seq bigint, sender_device uuid, kind text, epoch bigint, ciphertext bytea, ttl_s int,
               created_at timestamptz, expires_at timestamptz, hard_expires_at timestamptz)
language plpgsql security definer set search_path = public as $$
begin
  perform chat_my_device(p_device);
  if not exists (select 1 from chat_members m join chat_rooms r on r.id = m.room_id
                 where m.room_id = p_room and m.device_id = p_device and m.state in ('active','pending')
                   and r.state = 'active' and r.expires_at > now()) then
    raise exception 'not_a_member';
  end if;
  update chat_deliveries d set delivered_at = now()
  from chat_messages m where d.message_id = m.id and m.room_id = p_room and d.device_id = p_device and d.delivered_at is null and m.seq > p_after;
  return query
    select m.id, m.seq, m.sender_device, m.kind, m.epoch, m.ciphertext, m.ttl_s, m.created_at, d.expires_at, m.hard_expires_at
    from chat_messages m
    left join chat_deliveries d on d.message_id = m.id and d.device_id = p_device
    where m.room_id = p_room and m.seq > p_after and m.hard_expires_at > now()
      and m.sender_device <> p_device
      and (m.to_device is null or m.to_device = p_device)
      and (m.kind <> 'app' or (d.message_id is not null and (d.expires_at is null or d.expires_at > now())))
    order by m.seq
    limit least(p_limit, 500);
end $$;

-- Starts a recipient's countdown the first time they open a message. Repeats don't extend it.
create or replace function public.chat_mark_opened(p_message uuid, p_device uuid)
returns timestamptz language plpgsql security definer set search_path = public as $$
declare v timestamptz;
begin
  perform chat_my_device(p_device);
  update chat_deliveries d
  set opened_at = now(), expires_at = least(coalesce(d.expires_at, 'infinity'), now() + make_interval(secs => m.ttl_s), m.hard_expires_at)
  from chat_messages m
  where d.message_id = p_message and d.device_id = p_device and m.id = d.message_id and d.opened_at is null
  returning d.expires_at into v;
  if v is null then
    select d.expires_at into v from chat_deliveries d where d.message_id = p_message and d.device_id = p_device;
  end if;
  return v;
end $$;

-- ---------------------------------------------------------------------------- attachments

create or replace function public.chat_register_attachment(p_room uuid, p_device uuid, p_id uuid, p_size bigint, p_view_once boolean, p_ttl_s int)
returns text language plpgsql security definer set search_path = public as $$
declare v_path text := p_room::text || '/' || p_id::text; r chat_rooms%rowtype;
begin
  perform chat_my_device(p_device);
  if not chat_is_member(p_room) then raise exception 'not_a_member'; end if;
  if not chat_rate_ok('attach', p_device::text, 30, interval '10 minutes') then raise exception 'rate_limited'; end if;
  select * into r from chat_rooms where id = p_room;
  insert into chat_attachments(id, room_id, object_path, size, view_once, expires_at)
  values (p_id, p_room, v_path, p_size, p_view_once,
          least(now() + make_interval(secs => greatest(coalesce(p_ttl_s, r.default_ttl_s), 3600)), now() + make_interval(secs => r.max_unopened_s), r.expires_at));
  return v_path;
end $$;

-- View-once: the first claim leaves a 2-minute download window, then access ends.
create or replace function public.chat_claim_attachment(p_id uuid)
returns text language plpgsql security definer set search_path = public as $$
declare a chat_attachments%rowtype;
begin
  select * into a from chat_attachments where id = p_id for update;
  if not found or a.revoked_at is not null or a.expires_at <= now() or not chat_is_member(a.room_id) then raise exception 'gone'; end if;
  if a.view_once then
    update chat_attachments set revoked_at = now() + interval '2 minutes' where id = p_id;
  end if;
  return a.object_path;
end $$;

create or replace function public.chat_attachment_readable(p_name text)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from chat_attachments a
                 where a.object_path = p_name and a.expires_at > now()
                   and (a.revoked_at is null or a.revoked_at > now())
                   and chat_is_member(a.room_id));
$$;

create or replace function public.chat_attachment_writable(p_name text)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from chat_attachments a
                 where a.object_path = p_name and a.created_at > now() - interval '30 minutes'
                   and a.revoked_at is null and chat_is_member(a.room_id));
$$;

