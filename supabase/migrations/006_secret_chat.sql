-- ---------------------------------------------------------------------------- leave, burn

create or replace function public.chat_leave(p_room uuid, p_device uuid)
returns void language plpgsql security definer set search_path = public as $$
begin
  perform chat_my_device(p_device);
  update chat_members set state = 'removed', removed_at = now() where room_id = p_room and device_id = p_device and state <> 'removed';
  delete from chat_deliveries d using chat_messages m where d.message_id = m.id and m.room_id = p_room and d.device_id = p_device;
  perform chat_ping(p_room, 'member_removed', jsonb_build_object('device', p_device));
end $$;

-- Owner only. Revokes everything server-side at once; clients wipe local keys on the ping.
create or replace function public.chat_burn(p_room uuid)
returns int language plpgsql security definer set search_path = public as $$
declare n int;
begin
  update chat_rooms set state = 'burned', burned_at = now() where id = p_room and owner = auth.uid() and state = 'active';
  if not found then raise exception 'not_owner'; end if;
  update chat_invites set revoked_at = now() where room_id = p_room and revoked_at is null;
  update chat_members set state = 'removed', removed_at = now(), key_package = null where room_id = p_room and state <> 'removed';
  delete from chat_messages where room_id = p_room;
  insert into chat_storage_trash(object_path) select object_path from chat_attachments where room_id = p_room on conflict do nothing;
  delete from chat_attachments where room_id = p_room;
  get diagnostics n = row_count;
  perform chat_ping(p_room, 'burned', '{}'::jsonb);
  perform chat_log('room_burned', p_room);
  return n;
end $$;

-- ---------------------------------------------------------------------------- reaper

-- Idempotent; safe to run every minute and to retry.
create or replace function public.chat_reap()
returns jsonb language plpgsql security definer set search_path = public as $$
declare d int; m int; a int; r int;
begin
  delete from chat_deliveries where expires_at <= now();
  get diagnostics d = row_count;
  -- App messages with no live recipient left, and anything past its hard expiry.
  delete from chat_messages x where x.hard_expires_at <= now()
     or (x.kind = 'app' and not exists (select 1 from chat_deliveries y where y.message_id = x.id));
  get diagnostics m = row_count;
  with gone as (
    delete from chat_attachments where expires_at <= now() or (revoked_at is not null and revoked_at <= now())
    returning object_path)
  insert into chat_storage_trash(object_path) select object_path from gone on conflict do nothing;
  get diagnostics a = row_count;
  with dead as (
    delete from chat_rooms where (state = 'active' and expires_at <= now()) or (state = 'burned' and burned_at < now() - interval '1 day')
    returning id)
  select count(*) into r from dead;
  delete from chat_key_packages where consumed_at is not null or created_at < now() - interval '30 days';
  delete from chat_rate_limits where window_start < now() - interval '1 day';
  delete from chat_security_events where created_at < now() - interval '30 days';
  return jsonb_build_object('deliveries', d, 'messages', m, 'attachments', a, 'rooms', r);
end $$;

-- Rooms deleted by the reaper cascade to attachments without queuing their objects; catch that.
create or replace function public.chat_trash_attachment() returns trigger language plpgsql security definer set search_path = public as $$
begin insert into chat_storage_trash(object_path) values (old.object_path) on conflict do nothing; return old; end $$;
drop trigger if exists chat_attachments_trash on public.chat_attachments;
create trigger chat_attachments_trash after delete on public.chat_attachments for each row execute function public.chat_trash_attachment();

-- ---------------------------------------------------------------------------- admin (aggregates only)

create or replace function public.chat_admin_stats()
returns jsonb language plpgsql stable security definer set search_path = public as $$
begin
  if not exists (select 1 from chat_admins where user_id = auth.uid()) then raise exception 'forbidden'; end if;
  return jsonb_build_object(
    'active_rooms', (select count(*) from chat_rooms where state = 'active' and expires_at > now()),
    'messages_held', (select count(*) from chat_messages),
    'messages_24h', (select count(*) from chat_messages where created_at > now() - interval '1 day'),
    'attachments_bytes', (select coalesce(sum(size), 0) from chat_attachments),
    'storage_trash', (select count(*) from chat_storage_trash),
    'rate_limited_24h', (select count(*) from chat_security_events where kind like 'rate_limited:%' and created_at > now() - interval '1 day'),
    'security_24h', (select coalesce(jsonb_object_agg(kind, n), '{}') from (select kind, count(*) n from chat_security_events
                       where created_at > now() - interval '1 day' and kind not like 'rate_limited:%' group by kind) s));
end $$;

-- ---------------------------------------------------------------------------- realtime authorization
-- Members may subscribe to their room's private channel. No insert policy: only the server publishes.
do $$ begin
  if exists (select 1 from information_schema.tables where table_schema = 'realtime' and table_name = 'messages') then
    execute 'drop policy if exists "chat members receive" on realtime.messages';
    execute $p$create policy "chat members receive" on realtime.messages for select to authenticated
      using (realtime.topic() like 'room:%' and public.chat_is_member(substring(realtime.topic() from 6)::uuid))$p$;
  end if;
end $$;

