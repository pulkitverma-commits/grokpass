// Config plugin (N3, Android): opts the app out of Auto Backup and device-to-device transfer by
// declaring rules that exclude every domain (root, file, database, sharedpref, external), and
// references them from the manifest:
//   android:dataExtractionRules  (Android 12+, API 31+)  -> res/xml/onepeek_data_extraction_rules.xml
//   android:fullBackupContent    (Android 11 and lower)  -> res/xml/onepeek_backup_rules.xml
// `android.allowBackup: false` is already set in app.config.ts by the lead; these rules are the belt
// to that brace (allowBackup=false alone is honoured by Auto Backup, but a future `true`, an OEM
// transfer tool or a debug `adb backup` would otherwise take the SQLite file and SharedPreferences).
//
// Format: https://developer.android.com/identity/data/autobackup
//   <data-extraction-rules><cloud-backup/><device-transfer/></data-extraction-rules>, legacy
//   <full-backup-content>; every include/exclude needs `domain` and `path`; "." is the domain root
//   and a directory path covers its subtree.
// Mods: `withDangerousMod('android')` writes the two XML files under
//   <platformProjectRoot>/app/src/main/res/xml (dangerous mods run before the manifest mod, see
//   expo/config-plugins build/plugins/withDangerousMod.d.ts); `withAndroidManifest` sets the two
//   attributes on <application> (AndroidConfig.Manifest.getMainApplicationOrThrow).
// expo-secure-store ships its own rules for the same attributes; app.config.ts passes
//   `configureAndroidBackup: false` to it so the two plugins do not fight (its docs say to exclude
//   the SecureStore shared_prefs yourself in that case — covered by excluding `sharedpref` entirely).
const fs = require('fs');
const path = require('path');
const { withAndroidManifest, withDangerousMod, AndroidConfig, createRunOncePlugin } = require('expo/config-plugins');

const BACKUP_RULES_NAME = 'onepeek_backup_rules';
const DATA_EXTRACTION_RULES_NAME = 'onepeek_data_extraction_rules';

const DOMAINS = ['root', 'file', 'database', 'sharedpref', 'external'];

const excludes = (indent) => DOMAINS.map((d) => `${indent}<exclude domain="${d}" path="." />`).join('\n');

const BACKUP_RULES_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withBackupRules.js: OnePeek keeps no backup of keys or messages. -->
<full-backup-content>
${excludes('  ')}
</full-backup-content>
`;

const DATA_EXTRACTION_RULES_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withBackupRules.js: OnePeek keeps no backup of keys or messages. -->
<data-extraction-rules>
  <cloud-backup disableIfNoEncryptionCapabilities="true">
${excludes('    ')}
  </cloud-backup>
  <device-transfer>
${excludes('    ')}
  </device-transfer>
</data-extraction-rules>
`;

/** Pure manifest transform (unit-tested): points <application> at the two rule files. */
function setBackupAttributes(androidManifest) {
  const app = AndroidConfig.Manifest.getMainApplicationOrThrow(androidManifest);
  app.$['android:allowBackup'] = 'false';
  app.$['android:fullBackupContent'] = `@xml/${BACKUP_RULES_NAME}`;
  app.$['android:dataExtractionRules'] = `@xml/${DATA_EXTRACTION_RULES_NAME}`;
  return androidManifest;
}

/** Writes the two XML resources. Exported for the unit test (takes any directory). */
function writeRuleFiles(resXmlDir) {
  fs.mkdirSync(resXmlDir, { recursive: true });
  fs.writeFileSync(path.join(resXmlDir, `${BACKUP_RULES_NAME}.xml`), BACKUP_RULES_XML);
  fs.writeFileSync(path.join(resXmlDir, `${DATA_EXTRACTION_RULES_NAME}.xml`), DATA_EXTRACTION_RULES_XML);
}

const withBackupRules = (config) => {
  config = withDangerousMod(config, [
    'android',
    async (cfg) => {
      writeRuleFiles(path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res', 'xml'));
      return cfg;
    },
  ]);
  return withAndroidManifest(config, (cfg) => {
    cfg.modResults = setBackupAttributes(cfg.modResults);
    return cfg;
  });
};

module.exports = createRunOncePlugin(withBackupRules, 'onepeek-backup-rules', '1.0.0');
module.exports.setBackupAttributes = setBackupAttributes;
module.exports.writeRuleFiles = writeRuleFiles;
module.exports.BACKUP_RULES_XML = BACKUP_RULES_XML;
module.exports.DATA_EXTRACTION_RULES_XML = DATA_EXTRACTION_RULES_XML;
module.exports.DOMAINS = DOMAINS;
