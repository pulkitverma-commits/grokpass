do $$ declare f text; begin
  foreach f in array array[
    'chat_register_device(bytea,text)', 'chat_upload_key_packages(uuid,bytea[])', 'chat_list_devices()',
    'chat_revoke_device(uuid)', 'chat_create_room(uuid,text,int,text,int,text)', 'chat_my_rooms()',
    'chat_room_members(uuid)', 'chat_set_timer(uuid,int,text)', 'chat_create_invite(uuid,text,int,int,boolean)',
    'chat_revoke_invite(uuid)', 'chat_list_invites(uuid)', 'chat_peek_invite(text)',
    'chat_redeem_invite(text,uuid,bytea,text)',
    'chat_send(uuid,uuid,uuid,text,bigint,bytea,uuid,int,uuid[],uuid[])', 'chat_fetch(uuid,uuid,bigint,int)',
    'chat_mark_opened(uuid,uuid)', 'chat_register_attachment(uuid,uuid,uuid,bigint,boolean,int)',
    'chat_claim_attachment(uuid)', 'chat_leave(uuid,uuid)', 'chat_burn(uuid)', 'chat_admin_stats()'] loop
    execute format('revoke all on function public.%s from public, anon', f);
    execute format('grant execute on function public.%s to authenticated', f);
  end loop;
  foreach f in array array['chat_log(text,uuid,uuid)', 'chat_rate_ok(text,text,int,interval)', 'chat_my_device(uuid)',
    'chat_ping(uuid,text,jsonb)', 'chat_reap()', 'chat_trash_attachment()'] loop
    execute format('revoke all on function public.%s from public, anon, authenticated', f);
    execute format('grant execute on function public.%s to service_role', f);
  end loop;
  -- Used inside RLS / storage policies, so authenticated must be able to call them.
  foreach f in array array['chat_is_member(uuid)', 'chat_attachment_readable(text)', 'chat_attachment_writable(text)'] loop
    execute format('revoke all on function public.%s from public, anon', f);
    execute format('grant execute on function public.%s to authenticated', f);
  end loop;
end $$;

-- ---------------------------------------------------------------------------- schedule
-- Every minute. Needs the pg_cron extension (Database → Extensions). Skipped quietly if absent;
-- /api/chat/cleanup (Vercel cron) also calls chat_reap() and empties chat_storage_trash.
do $$ begin
  create extension if not exists pg_cron;
  perform cron.unschedule('chat-reap') where exists (select 1 from cron.job where jobname = 'chat-reap');
  perform cron.schedule('chat-reap', '* * * * *', 'select public.chat_reap()');
exception when others then raise notice 'pg_cron unavailable: %', sqlerrm;
end $$;
